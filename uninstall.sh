#!/usr/bin/env bash
# Desinstala lo creado por install.sh. Funciona sin el release extraído: el
# instalador deja una copia en ~/.local/share/parlar/uninstall.sh y el comando
# parlar-uninstall apunta a ella. Por defecto conserva configuración y datos.
set -euo pipefail

main() {
DATA_BASE="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_BASE="${XDG_CONFIG_HOME:-$HOME/.config}"
# La copia instalada se reconoce por installed.json a su lado: desinstala la
# raíz donde vive aunque XDG_DATA_HOME haya cambiado desde la instalación.
PROPIO_DIR="$(dirname -- "$(readlink -f -- "${BASH_SOURCE[0]}")")"
RAIZ_PREDETERMINADA="$DATA_BASE/parlar"
if [[ -z "${PARLAR_INSTALL_HOME:-}" && "$(basename -- "$PROPIO_DIR")" == parlar \
        && -f "$PROPIO_DIR/installed.json" && -f "$PROPIO_DIR/uninstall.sh" ]]; then
    RAIZ_PREDETERMINADA="$PROPIO_DIR"
fi
INSTALL_HOME_ORIGINAL="${PARLAR_INSTALL_HOME:-$RAIZ_PREDETERMINADA}"
INSTALL_HOME="$INSTALL_HOME_ORIGINAL"
BIN_DIR="${PARLAR_BIN_DIR:-$HOME/.local/bin}"
DESKTOP_PATH="$DATA_BASE/applications/parlar.desktop"
ICON_PATH="$DATA_BASE/icons/hicolor/scalable/apps/parlar.svg"
UNIT_PATH="$CONFIG_BASE/systemd/user/parlar.service"
AUTOSTART_PATH="$CONFIG_BASE/autostart/parlar-systemd.desktop"
LEGACY_ENABLE_PATH="$CONFIG_BASE/systemd/user/default.target.wants/parlar.service"
CONFIG_DIR="$CONFIG_BASE/parlar"
PURGE_DATA=0

uso() {
    cat <<'EOF'
Uso: ./uninstall.sh [--purge-data]
     parlar-uninstall [--purge-data]

Desinstala ParlAR de la cuenta de usuario.
Por defecto conserva la configuración (~/.config/parlar) y los transcripts
(~/.local/share/parlar/sesiones).

  --purge-data  elimina también la configuración y los transcripts de ParlAR
  -h, --help    muestra esta ayuda sin modificar el sistema

Los modelos de Whisper descargados viven en ~/.cache/huggingface, una caché
que pueden compartir otros programas: nunca se borra automáticamente.
EOF
}

while (($#)); do
    case "$1" in
        --purge-data)
            PURGE_DATA=1
            ;;
        -h|--help)
            uso
            exit 0
            ;;
        *)
            echo "!! opción desconocida: $1" >&2
            uso >&2
            exit 2
            ;;
    esac
    shift
done

# ``test -L ruta/`` sigue el enlace por el separador final. Colapsamos solo
# separadores finales, preservando la identidad léxica de la raíz que se va a
# comprobar y usar. Los componentes . y .. se rechazan: normalizarlos podría
# cambiar qué enlace se inspecciona respecto del path que luego recibe rm.
while [[ "$INSTALL_HOME" != "/" && "$INSTALL_HOME" == */ ]]; do
    INSTALL_HOME="${INSTALL_HOME%/}"
done
case "$INSTALL_HOME" in
    */./*|*/.|*/../*|*/..)
        echo "!! ruta de instalación insegura: $INSTALL_HOME_ORIGINAL" >&2
        exit 1
        ;;
esac

if [[ "$INSTALL_HOME" != /* \
        || "$(basename -- "$INSTALL_HOME")" != "parlar" \
        || "$(dirname -- "$INSTALL_HOME")" == "/" ]]; then
    echo "!! ruta de instalación insegura: $INSTALL_HOME_ORIGINAL" >&2
    exit 1
fi
case "$INSTALL_HOME" in
    /|"$HOME"|"$HOME"/)
        echo "!! se rechaza borrar una ruta amplia: $INSTALL_HOME" >&2
        exit 1
        ;;
esac
case "$CONFIG_DIR" in
    /parlar|"$HOME"/parlar)
        echo "!! ruta de configuración insegura: $CONFIG_DIR" >&2
        exit 1
        ;;
esac

es_generado() {
    local ruta="$1"
    local marca="$2"
    [[ -f "$ruta" && ! -L "$ruta" ]] && IFS= read -r primera <"$ruta" \
        && [[ "$primera" == "$marca"* ]]
}

colapsar_separadores() {
    local valor="$1"
    while [[ "$valor" == *//* ]]; do
        valor="${valor//\/\//\/}"
    done
    printf '%s' "$valor"
}

# Targets propios: layout 1.1 (current), legacy 1.0.x (venv) y el uninstall.
es_target_propio() {
    local target
    target="$(colapsar_separadores "$1")"
    local comando="$2"
    case "$comando" in
        parlar-uninstall)
            [[ "$target" == "$INSTALL_HOME/uninstall.sh" ]]
            ;;
        *)
            [[ "$target" == "$INSTALL_HOME/current/venv/bin/$comando" \
                || "$target" == "$INSTALL_HOME/venv/bin/$comando" ]]
            ;;
    esac
}

# Borra un árbol propio sin seguir un symlink colocado en su lugar.
borrar_propio() {
    local ruta="$1"
    if [[ -L "$ruta" ]]; then
        rm -f -- "$ruta"
    elif [[ -e "$ruta" ]]; then
        rm -rf -- "$ruta"
    fi
}

if es_generado "$UNIT_PATH" "# Generated by ParlAR setup.sh."; then
    if command -v systemctl >/dev/null 2>&1; then
        systemctl --user stop parlar.service >/dev/null 2>&1 || true
        systemctl --user disable parlar.service >/dev/null 2>&1 || true
    fi
    if [[ -L "$LEGACY_ENABLE_PATH" ]]; then
        rm -f -- "$LEGACY_ENABLE_PATH"
    fi
    rm -f -- "$UNIT_PATH"
fi

if es_generado "$AUTOSTART_PATH" "# Generated by ParlAR install.sh."; then
    rm -f -- "$AUTOSTART_PATH"
fi

if es_generado "$DESKTOP_PATH" "# Generated by ParlAR install.sh."; then
    rm -f -- "$DESKTOP_PATH"
fi

if es_generado "$ICON_PATH" "<!-- Generated by ParlAR install.sh."; then
    rm -f -- "$ICON_PATH"
fi

for comando in parlar parlarctl parlar-uninstall; do
    destino="$BIN_DIR/$comando"
    if [[ -L "$destino" ]]; then
        target="$(readlink -- "$destino")"
        if es_target_propio "$target" "$comando"; then
            rm -f -- "$destino"
        fi
    fi
done

if [[ -L "$INSTALL_HOME" ]]; then
    echo "!! la raíz de instalación es un enlace simbólico; no se sigue ni elimina: $INSTALL_HOME" >&2
elif [[ -d "$INSTALL_HOME" ]]; then
    borrar_propio "$INSTALL_HOME/current"
    borrar_propio "$INSTALL_HOME/versions"
    borrar_propio "$INSTALL_HOME/venv"
    rm -f -- "$INSTALL_HOME/installed.json"
    if [[ -f "$INSTALL_HOME/uninstall.sh" || -L "$INSTALL_HOME/uninstall.sh" ]]; then
        # Bash ya abrió este script: borrarlo no interrumpe la ejecución.
        rm -f -- "$INSTALL_HOME/uninstall.sh"
    fi
    if ((PURGE_DATA)); then
        borrar_propio "$INSTALL_HOME/sesiones"
    fi
    rmdir -- "$INSTALL_HOME" 2>/dev/null || true
fi

if ((PURGE_DATA)); then
    borrar_propio "$CONFIG_DIR"
fi

if command -v systemctl >/dev/null 2>&1; then
    systemctl --user daemon-reload >/dev/null 2>&1 || true
fi
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$DATA_BASE/applications" >/dev/null 2>&1 || true
fi

if ((PURGE_DATA)); then
    echo "==> ParlAR desinstalado. Se eliminaron también su configuración y sus transcripts."
else
    echo "==> ParlAR desinstalado. Configuración, transcripts y otros datos fueron preservados."
    echo "    Para eliminarlos también: parlar-uninstall --purge-data (o ./uninstall.sh --purge-data)"
fi
echo "    Los modelos de Whisper descargados siguen en ~/.cache/huggingface,"
echo "    que pueden compartir otros programas. Para borrar sólo los de ParlAR:"
echo "      rm -rf ~/.cache/huggingface/hub/models--Systran--faster-whisper-*"
echo "    Si ParlAR sigue abierto, cerralo desde su ícono en la bandeja."
}

main "$@"
exit
